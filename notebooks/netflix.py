gs_knn.fit(X_train, y_train)
print("Best KNN:", gs_knn.best_params_)

# 7. Best model evaluation
best_model = gs_logit if gs_logit.best_score_ >= gs_knn.best_score_ else gs_knn
best_name = "LogisticRegression" if best_model is gs_logit else "KNN"

