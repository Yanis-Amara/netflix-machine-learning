print("Saved best model to:", best_path)

# 8. Clustering (K-Means)
tfidf = TfidfVectorizer(max_features=5000, min_df=3, ngram_range=(1,2))
X_text = tfidf.fit_transform(df["text_all"])

sil = {}
for k in range(3, 9):
    km = KMeans(n_clusters=k, n_init=10)
    labels = km.fit_predict(X_text)
    score = silhouette_score(X_text, labels)
    sil[k] = score

best_k = max(sil, key=sil.get)
print("Best K:", best_k)

km = KMeans(n_clusters=best_k, n_init=10)
clusters = km.fit_predict(X_text)

df_clust = df[["title", "listed_in", "type", "release_year"]]
df_clust["cluster"] = clusters

for c in range(best_k):
    print(f"\n=== CLUSTER {c} ===")
    print(df_clust[df_clust["cluster"] == c].head(10))

